"""Распознанный текст 456-ФЗ → формат базы знаний data/raw/law/*.txt («Статья N. …», части «1.», пункты «1)»).

    python scripts/import/struct_456fz.py fz456_ocr.txt data/raw/law/fz456.txt

Строки склеиваются в сплошной текст, затем режутся на статьи, части и пункты — только по порядку номеров
(«части 4 статьи 1.» внутри предложения не открывает новую часть). Ошибки распознавания, сверенные со сканом,
исправляются списком FIXES; если исправление не нашлось в тексте, скрипт об этом пишет.
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
raw = open(src, encoding="utf-8").read()
pages = re.split(r"^=== \d+\s*$", raw, flags=re.M)
text = []
for page in pages:
    lines = [l.strip() for l in page.splitlines() if l.strip()]
    # номер страницы в начале и штамп/мусор с цифрами в конце первой страницы
    if lines and re.fullmatch(r"\d{1,2}", lines[0]):
        lines = lines[1:]
    text.append(" ".join(lines))
s = " ".join(text)
s = re.sub(r"\[ОИ.*?\d{5,}\s*\d*", " ", s)              # штамп на первой странице
s = re.sub(r"\s+", " ", s)
s = s.replace("РОССИИСКАЯ", "РОССИЙСКАЯ").replace("статьи |", "статьи 1").replace(" — ", " ")
s = re.sub(r"(\d)\.([А-ЯЁ])", r"\1. \2", s)               # «1.В соответствии»
s = re.sub(r"№(\d)", r"№ \1", s)
s = re.sub(r"(?<=[а-яё])- (?=[а-яё])", "", s)
# ошибки распознавания, сверенные со сканом
FIXES = [
    ("(далее - эксперимент). 5 ", "(далее - эксперимент). "), ("в Целях", "в целях"),
    ("частью1] статьи 5 Федерального", "частью 1 статьи 5 Федерального"),
    ("в части] настоящей статьи", "в части 1 настоящей статьи"), ("либо В правоотношения", "либо в правоотношения"),
    ("статьей 4? Федерального", "статьей 4.5 Федерального"), ("в ‘территориальный", "в территориальный"),
    ("частей3 и 4", "частей 3 и 4"), (" 1]1. В случае", " 11. В случае"), ("частью 1] настоящей", "частью 11 настоящей"),
    ("в течение И этого", "в течение этого"), ("начинаяс 1-го", "начиная с 1-го"), ("в части | настоящей", "в части 1 настоящей"),
    ("в части 1] статьи 5", "в части 11 статьи 5"), ("в частях | - 3", "в частях 1 - 3"), ("в И соответствии", "в соответствии"),
    ("2)100 процентам", "2) 100 процентам"), ("части| статьи 7", "части 1 статьи 7"),
    ("страховых взносов По добровольным", "страховых взносов по добровольным"),
]
for a, b in FIXES:
    if a not in s:
        print("нет в тексте:", a)
    s = s.replace(a, b)
s = re.sub(r"(вступает в силу с 1 января 2026 года\.).*$", r"\1", s)
s = s.replace("Статья 10. Вступление в силу настоящего Федерального закона Настоящий",
              "Статья 10. Вступление в силу настоящего Федерального закона 1. Настоящий")

# заголовок закона до «Статья 1.»
head, _, body = s.partition("Статья 1.")
body = "Статья 1." + body
out_lines = ["# Федеральный закон от 15.12.2025 № 456-ФЗ «О проведении эксперимента по добровольному вступлению "
             "отдельных категорий граждан в правоотношения по обязательному социальному страхованию на случай "
             "временной нетрудоспособности»",
             "# Текст распознан с официальной публикации: http://publication.pravo.gov.ru/document/0001202512150018",
             ""]

# статьи
articles = re.split(r"(?=Статья \d{1,2}\.)", body)
for art in articles:
    if not art.strip():
        continue
    m = re.match(r"Статья (\d{1,2})\.\s*(.*)", art)
    number, rest = m[1], m[2]
    # название статьи — до первой части «1.»
    tm = re.search(r"\s1\.\s+[А-ЯЁ]", " " + rest)
    if tm:
        title, rest = rest[:tm.start()].strip(), rest[tm.start():].strip()
    else:
        title, rest = rest.strip(), ""
    # мусорная «1» после названия (номер страницы, попавший в текст)
    title = re.sub(r"\s+\d$", "", title)
    out_lines.append(f"Статья {number}. {title}")
    out_lines.append("@url http://publication.pravo.gov.ru/document/0001202512150018")
    # части по порядку номеров, пункты по порядку внутри части
    part_no, item_no = 0, 0
    pieces = []
    tokens = re.split(r"(\s(?:\d{1,2})\.\s+(?=[А-ЯЁ])|\s(?:\d{1,2})\)\s+(?=[А-ЯЁа-яё0-9«\"]))", " " + rest)
    cur = ""
    for t in tokens:
        mp = re.fullmatch(r"\s(\d{1,2})\.\s+", t or "")
        mi = re.fullmatch(r"\s(\d{1,2})\)\s+", t or "")
        if mp and int(mp[1]) == part_no + 1:
            if cur.strip():
                pieces.append(cur.strip())
            part_no, item_no, cur = int(mp[1]), 0, f"{mp[1]}. "
        elif mi and int(mi[1]) == item_no + 1:
            if cur.strip():
                pieces.append(cur.strip())
            item_no, cur = int(mi[1]), f"{mi[1]}) "
        else:
            cur += t or ""
    if cur.strip():
        pieces.append(cur.strip())
    out_lines += [p for p in pieces if p]
    out_lines.append("")

open(out, "w", encoding="utf-8").write("\n".join(out_lines))
print(len(articles), "статей")
